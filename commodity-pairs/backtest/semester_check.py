"""The "42% semester" check: how often does a long/short gold-pair strategy make 42% in one school semester,
and how does that compare with random pairs?

    .venv/bin/python -m backtest.semester_check

A semester is taken as 90 NYSE sessions (about 18 weeks). Every overlapping 90-session window of each strategy's
out-of-sample daily net returns (2016-10 -> 2026-10) counts as one "semester". Gold pairs reuse the saved trial
files from run_all; the random-pair comparison re-runs the same engine on random pairs from the same universe.
The owner's trade was discretionary and its leverage is unknown, so results are shown at 1x gross (the research
setting) and at 2x gross (approximated as 2 x daily net return, i.e. costs and borrow scale with leverage too).
Reads only the frozen cache. Writes research/semester_42pct.md and backtest/results/semester_42pct.csv.
"""
from __future__ import annotations

import multiprocessing as mp
import warnings

import numpy as np
import pandas as pd

from . import baseline, config, data, screen, walkforward
from .trading_calendar import sessions, walk_forward_grid

SEMESTER = 90
TARGET = 0.42
RULES = ("rotation", "coint_ols")
N_RANDOM = 200
OUT_MD = config.RESEARCH_DIR / "semester_42pct.md"
OUT_CSV = config.RESULTS_DIR / "semester_42pct.csv"

_CTX: dict = {}


def semester_returns(net_ret: np.ndarray, leverage: float) -> np.ndarray:
    """Compounded return of every overlapping SEMESTER-session window."""
    r = np.clip(leverage * np.asarray(net_ret, dtype=float), -0.99, None)
    logc = np.concatenate([[0.0], np.cumsum(np.log1p(r))])
    if len(r) < SEMESTER:
        return np.array([])
    return np.expm1(logc[SEMESTER:] - logc[:-SEMESTER])


def _run_random(task):
    pid, a, b, rule = task
    pdat = walkforward.build_pair_data(_CTX["panel"], _CTX["screen"], pid, a, b)
    res = walkforward.run_pair_rule(rule, pdat, _CTX["windows"])
    return pid, rule, res.daily["net_ret"].to_numpy()[1:]


def summarize(label: str, group: str, rule: str, series: list[np.ndarray]) -> dict:
    row = {"group": group, "label": label, "rule": rule, "n_strategies": len(series)}
    for lev in (1.0, 2.0):
        sem = np.concatenate([semester_returns(s, lev) for s in series]) if series else np.array([])
        tag = f"{int(lev)}x"
        row[f"n_semesters_{tag}"] = len(sem)
        row[f"share_ge_42pct_{tag}"] = float((sem >= TARGET).mean()) if len(sem) else np.nan
        row[f"share_le_minus_30pct_{tag}"] = float((sem <= -0.30).mean()) if len(sem) else np.nan
        row[f"median_{tag}"] = float(np.median(sem)) if len(sem) else np.nan
        row[f"p95_{tag}"] = float(np.quantile(sem, 0.95)) if len(sem) else np.nan
        row[f"best_{tag}"] = float(sem.max()) if len(sem) else np.nan
    return row


def main() -> None:
    warnings.filterwarnings("ignore")
    sess = sessions()
    windows = walk_forward_grid(sess)
    frames, missing = data.load_all(data.all_tickers())
    panel = data.build_panel(frames, sess)
    sc = pd.read_csv(config.SCREEN_PATH)
    pool = pd.read_csv(config.RESULTS_DIR / "tested_pairs.csv")
    cands = data.candidate_pairs()

    rows, per_pair = [], []
    gold = pool[pool["group"] == "precious_metals"]
    for rule in RULES:
        series = []
        for r in gold.itertuples():
            d = pd.read_csv(config.TRIALS_DIR / f"{r.pair_id}__{rule}.csv.gz", index_col=0)
            s = d["net_ret"].to_numpy()[1:]
            series.append(s)
            per_pair.append(summarize(r.pair_id, "gold pair", rule, [s]))
        rows.append(summarize("all gold/precious-metal pairs", "gold pairs", rule, series))

    rng = np.random.default_rng([config.SEED, 42])
    rnd = baseline.draw_random_pairs(sc, cands, panel, sess, windows, N_RANDOM, rng)
    _CTX.update(panel=panel, screen=sc, windows=windows)
    tasks = [(pid, a, b, rule) for pid, a, b in rnd for rule in RULES]
    with mp.get_context("fork").Pool() as p:
        res = p.map(_run_random, tasks, chunksize=4)
    for rule in RULES:
        rows.append(summarize(f"{N_RANDOM} random pairs", "random pairs", rule, [s for _, ru, s in res if ru == rule]))

    out = pd.DataFrame(rows + per_pair)
    out.to_csv(OUT_CSV, index=False, float_format="%.6g")
    write_md(pd.DataFrame(rows), pd.DataFrame(per_pair))
    print(pd.DataFrame(rows).to_string(index=False))


def _pct(x: float) -> str:
    return "n/a" if not np.isfinite(x) else f"{100 * x:.1f}%"


def write_md(agg: pd.DataFrame, per_pair: pd.DataFrame) -> None:
    lines = [
        "# The \"42% semester\" check",
        "",
        "_Generated by `python -m backtest.semester_check` from the frozen cache. Every number comes from code._",
        "",
        "**The question:** in high school you made about 42% in one semester trading a long/short gold pair and flipping",
        "sides as the relationship swung. How often does that happen by mechanical rule, and is it more common for",
        "gold pairs than for random pairs?",
        "",
        "**Method:**",
        f"- A semester is {SEMESTER} NYSE sessions (about 18 weeks).",
        "- Every overlapping window in the out-of-sample period, Oct 2016 to Oct 2026, counts as one semester.",
        "- Strategies:",
        "  - `rotation`: the \"flip sides\" rule, long the stronger leg over the past 20 days and short the other;",
        "  - `coint_ols`: classic spread mean reversion.",
        "  - Both include realistic costs.",
        "- Your leverage is unknown, so results are shown at 1x gross (the research setting) and at 2x gross,",
        "  which is roughly fully long one leg and fully short the other.",
        "",
        "| strategies | rule | # | semesters ≥ +42% (1x) | semesters ≥ +42% (2x) | semesters ≤ −30% (2x) | median (2x) | best (2x) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in agg.itertuples():
        lines.append(f"| {r.label} | {r.rule} | {r.n_strategies} | {_pct(r.share_ge_42pct_1x)} | {_pct(r.share_ge_42pct_2x)} | "
                     f"{_pct(r.share_le_minus_30pct_2x)} | {_pct(r.median_2x)} | {_pct(r.best_2x)} |")
    lines += ["", "Per gold pair (2x gross):", "",
              "| pair | rule | semesters ≥ +42% | semesters ≤ −30% | median | best |", "|---|---|---|---|---|---|"]
    for r in per_pair.sort_values(["rule", "label"]).itertuples():
        lines.append(f"| {r.label} | {r.rule} | {_pct(r.share_ge_42pct_2x)} | {_pct(r.share_le_minus_30pct_2x)} | "
                     f"{_pct(r.median_2x)} | {_pct(r.best_2x)} |")
    lines += ["", "**How to read it:** if the share of +42% semesters for gold pairs is about the same as for random pairs,",
              "and big losing semesters show up about as often as big winning ones, then a single 42% semester is",
              "what luck plus leverage produces. It does not show a durable edge. The strategy-level tests in",
              "`backtest/results/summary.md` give the long-run answer.", ""]
    OUT_MD.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
