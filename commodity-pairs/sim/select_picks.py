"""Select the 5 near-miss pairs for the paper-trading system check, by code.

    .venv/bin/python -m sim.select_picks   ->  sim/picks.json, research/near_miss_selection.md

No pair passed the research bar (backtest/results/gates.csv: quant_pass is False everywhere). The owner chose to
paper-trade the best near-misses anyway, labeled FAILED_THE_BAR, purely to check that the live system behaves as
backtested. The rule is the review protocol's selection rule (research/REVIEW_PROTOCOL.md), applied to all trials:
  1. rank by DSR (max of full and post-COVID), then post-COVID Sharpe;
  2. skip a trial that shares a leg with an earlier pick;
  3. skip a trial whose daily OOS net returns correlate > 0.5 with an earlier pick's (overlapping dates);
  4. prefer a commodity group not yet represented (a second pass without this rule only if fewer than 5 are found).
"""
from __future__ import annotations

import json

import pandas as pd

from backtest import config

N_PICKS = 5
MAX_CORR = 0.5
PICKS_PATH = config.ROOT / "sim" / "picks.json"
MD_PATH = config.RESEARCH_DIR / "near_miss_selection.md"


def _returns(pair_id: str, rule: str) -> pd.Series:
    d = pd.read_csv(config.TRIALS_DIR / f"{pair_id}__{rule}.csv.gz", index_col=0, parse_dates=True)
    return d["net_ret"]


def select(gates: pd.DataFrame) -> tuple[list, list]:
    ranked = gates.assign(dsr_max=gates[["dsr_full", "dsr_post"]].max(axis=1))
    ranked = ranked.sort_values(["dsr_max", "post_sharpe"], ascending=False).reset_index(drop=True)
    for use_group in (True, False):
        picks, log = [], []
        for r in ranked.itertuples():
            if len(picks) == N_PICKS:
                break
            if any({r.leg_a, r.leg_b} & {p.leg_a, p.leg_b} for p in picks):
                log.append((r.pair_id, r.rule, "shares a leg with an earlier pick"))
                continue
            if use_group and any(r.group == p.group for p in picks):
                log.append((r.pair_id, r.rule, f"group {r.group} already represented"))
                continue
            x = _returns(r.pair_id, r.rule)
            corrs = [x.corr(_returns(p.pair_id, p.rule)) for p in picks]
            if corrs and max(corrs) > MAX_CORR:
                log.append((r.pair_id, r.rule, f"return correlation {max(corrs):.2f} > {MAX_CORR}"))
                continue
            picks.append(r)
        if len(picks) == N_PICKS:
            return picks, log
    return picks, log


def main() -> None:
    gates = pd.read_csv(config.RESULTS_DIR / "gates.csv")
    if gates["quant_pass"].any():
        raise SystemExit("some trial passed the gates: picks must come from the review loop, not this script")
    screen = pd.read_csv(config.SCREEN_PATH).set_index("ticker")
    picks, log = select(gates)
    out = []
    for i, p in enumerate(picks, 1):
        legs = (p.leg_a, p.leg_b)
        out.append({
            "pick_id": f"pick_{i}", "pair_id": p.pair_id, "leg_a": p.leg_a, "leg_b": p.leg_b, "rule": p.rule,
            "group": p.group, "status": "FAILED_THE_BAR", "fail_reasons": p.fail_reasons,
            "params": dict(config.PARAMS),
            "slippage_bps": {t: float(screen.loc[t, "slippage_bps"]) for t in legs},
            "borrow_rate": {t: float(screen.loc[t, "borrow_rate"]) for t in legs},
            "backtest": {"full_sharpe": p.full_sharpe, "post_sharpe": p.post_sharpe, "full_maxdd": p.full_maxdd,
                         "full_round_trips": int(p.full_round_trips), "dsr_full": p.dsr_full, "dsr_post": p.dsr_post},
            "backtest_daily_returns_path": f"backtest/results/trials/{p.pair_id}__{p.rule}.csv.gz",
            "backtest_trades_path": f"backtest/results/trials/{p.pair_id}__{p.rule}_trades.csv",
        })
    PICKS_PATH.write_text(json.dumps({"note": "NONE of these passed the research bar. They are paper-traded only to "
                                              "check that the live system behaves as backtested.",
                                      "picks": out}, indent=1) + "\n")
    lines = ["# Near-miss selection for the paper-trading system check", "",
             "_Generated by `python -m sim.select_picks` from `backtest/results/gates.csv`._", "",
             "**No pair passed the research bar.** These 5 are the best near-misses under the review protocol's",
             "selection rule. They are paper-traded only to check that the live system behaves as backtested, not as",
             "investment candidates.", "",
             "**Rule:**",
             "1. Rank all trials by DSR (the larger of the full and post-COVID values), then by post-COVID Sharpe.",
             "2. Skip a trial that shares a leg with an earlier pick.",
             f"3. Skip a trial whose daily returns correlate > {MAX_CORR} with an earlier pick's.",
             "4. Prefer a commodity group not yet represented.", "",
             "| pick | pair | rule | group | Sharpe full / post | max DD | round trips | DSR full / post | failed gates |",
             "|---|---|---|---|---|---|---|---|---|"]
    for o in out:
        b = o["backtest"]
        lines.append(f"| {o['pick_id']} | {o['leg_a']} / {o['leg_b']} | `{o['rule']}` | {o['group']} | "
                     f"{b['full_sharpe']:.2f} / {b['post_sharpe']:.2f} | {b['full_maxdd']:.1%} | {b['full_round_trips']} | "
                     f"{b['dsr_full']:.3f} / {b['dsr_post']:.3f} | {o['fail_reasons']} |")
    lines += ["", "Trials skipped on the way down the ranking:", ""]
    lines += [f"- {pid} `{rule}`: {why}" for pid, rule, why in log] or ["- none"]
    MD_PATH.write_text("\n".join(lines) + "\n")
    for o in out:
        print(o["pick_id"], o["pair_id"], o["rule"])


if __name__ == "__main__":
    main()
